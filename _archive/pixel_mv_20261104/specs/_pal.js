  at: function (fam, i) {
    var a = this.core[fam] || this.ext[fam];
    if (!a) throw new Error('P: 无此色族 ' + fam + '（新族请回写 _pal.js）');
    return a[Math.max(0, Math.min(a.length - 1, i | 0))];
  },

  // 把某族线性插值成 n 档（用于需要 7 档但族里只有 5 档的情况）
  ramp: function (fam, n) {
    var a = this.core[fam] || this.ext[fam];
    if (!a) throw new Error('P: 无此色族 ' + fam);
    var out = [], i, k, t, c1, c2, h;
    function num(s) { return parseInt(s.slice(1), 16); }
    for (i = 0; i < n; i++) {
      t = (n === 1) ? 0 : i / (n - 1) * (a.length - 1);
      k = Math.min(a.length - 2, Math.floor(t));
      t = t - k;
      c1 = num(a[k]); c2 = num(a[Math.min(a.length - 1, k + 1)]);
      h = '#';
      for (var s = 16; s >= 0; s -= 8) {
        var v = Math.round(((c1 >> s) & 255) * (1 - t) + ((c2 >> s) & 255) * t);
        h += ('0' + v.toString(16)).slice(-2);
      }
      out.push(h);
    }
    return out;
  },

