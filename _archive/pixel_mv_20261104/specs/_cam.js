// _cam.js — 运镜复用模块（2026-11-05 定稿，用户裁定"运镜也还可以"）
// ---------------------------------------------------------------
// 依赖：无（纯函数）。注入方式同 _pal.js / _fig.js。
//
// 全部结论来自 2026-11-05 对 20.25s 参考片的实测（颜色特征追踪 265px/s + 帧差切点检测）
// 与我方 10s demo 的落地验证。**七铁律**见 SKILL.md 第五节 2026-11-05 条目。
//
// 核心一句：像素 MV 的运镜不是"镜头语言"，是"长卷平移"。没有 3D 没有景深，
//          所谓推拉摇移全部等价于 translate 一张大图 + 窗口取景。
var CAM = {
  // ── 速度常量（格/秒 @ 320 基准）────────────────────────
  // 实测参考片横移 265px/s @1920 → 折算 320 基准 = 44 格/秒；
  // 我方落地取 80 格/秒 更快一档，观感更"走"，且 3 秒能走完 240 格（够 3 个店铺）。
  DROP: 48,     // 下摇 48 格/秒 = 2 格/帧 @24fps
  PAN: 80,      // 横移 80 格/秒
  PUSH: 1.6,    // 推镜倍率 1.5–1.8（⚠ 只有区间，没有精确值，参考片测不准）

  // ── 唯一合法的位移函数 ─────────────────────────────────
  // 铁律：整数格落点，禁缓动（像素画加速会"跳格"）。
  //   ❌ lt * 37.5           → 半格落点，抖动
  //   ❌ easeInOut(lt) * 100 → 速度变化，像素画读起来像卡顿
  //   ✅ Math.round(lt * speed)
  grid: function (lt, speed) {
    return Math.round(lt * (speed == null ? this.DROP : speed));
  },

  // 推镜：中心固定、只放大（scale 线性，禁缓动）
  pushAt: function (lt, dur, from, to) {
    from = from == null ? 1 : from;
    to = to == null ? this.PUSH : to;
    var k = dur > 0 ? Math.min(1, Math.max(0, lt / dur)) : 1;
    return from + (to - from) * k;
  },

  // ── 参考片 8 段结构（20.25s / 605 帧 @30fps）──────────
  // 前密后疏：前段切得碎（1.2–1.4s），后段给一个 5.2s 长镜压住情绪。
  STRUCT: [
    { seg: 1, name: '静止空镜', dur: 3.5, move: 'none', note: '开场先给 3.5s 不动，让人进入画面' },
    { seg: 2, name: '下摇穿越', dur: 3.0, move: 'drop', note: '云→楼群→街道，一镜到底不切' },
    { seg: 3, name: '横移街景', dur: 1.16, move: 'pan', note: '店铺逐个滑过' },
    { seg: 4, name: 'KTV', dur: 1.34, move: 'pan', note: '' },
    { seg: 5, name: '烟酒', dur: 1.23, move: 'pan', note: '' },
    { seg: 6, name: '街角', dur: 1.37, move: 'pan', note: '' },
    { seg: 7, name: '推镜', dur: 5.2, move: 'push', note: '全片最长镜，推住一个信息点不放' },
    { seg: 8, name: '室内', dur: 3.5, move: 'none', note: '收在静止，情绪落地' },
  ],
  // 时长比例：3.5/3.0/1.16/1.34/1.23/1.37/5.2/3.5 = 17%/15%/6%/7%/6%/7%/26%/17%

  // ── 实测切点（秒，20.25s 参考片）──────────────────────
  CUTS: [6.47, 7.63, 8.97, 10.20, 11.57, 16.77],

  // ── 转场基准时长（秒）────────────────────────────────
  // 同轴切点（都是横移接横移）时，切点要对齐地平线，否则观众会晕。
  XFADE: { fade: 0.4, blk: 0.24, dither: 0.3 },

  // ── 长卷画布尺寸 ──────────────────────────────────────
  // 下摇：总高 540（3 屏），窗口 180
  // 横移：总宽 760–980（视店铺数），窗口 320
  ROLL_H: 540,
  ROLL_W_MIN: 760,
};
