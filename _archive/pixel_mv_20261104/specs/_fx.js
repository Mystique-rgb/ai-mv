// _fx.js — 动效复用模块（2026-11-05，对标《陀飞轮》像素游戏 UI 版 278s 实测）
// ---------------------------------------------------------------
// 依赖：specs/_pal.js（P）。注入顺序 _pal → _fig → _cam → _fx → spec。
//
// 从对标片提炼的四条动效铁律（违反任何一条就"不像"）：
//   ① 一个焦点：每画面只有一个东西在动，其余全静止。
//   ② 离散化：所有变化都是跳格，禁平滑插值（心跳 3 档、数字整串替换）。
//   ③ 循环即生命：静态画面必有 idle 动效（旋转/心跳/粒子），否则读成"卡了"。
//   ④ 匀速：旋转和位移都恒速，禁缓动（与 _cam.js 同源）。
//
// 全部函数都是**纯数值函数**，自己接 canvas，不碰 ctx（除了 panelIn 的辅助）。
var FX = {

  // ══════════════════════════════════════════════════════
  // A. 匀速旋转（罗盘实测 85°/s，4.2s 一圈）
  //   spin(lt)              → 角度（度）
  //   spin(lt, 85)          → 同上
  //   spin(lt, -60)         → 逆时针
  // ⚠ 不许用 easeInOut 包它。像素画一缓动就成 PPT。
  // ══════════════════════════════════════════════════════
  spin: function (lt, dps) { return (lt * (dps == null ? 85 : dps)) % 360; },

  // ══════════════════════════════════════════════════════
  // B. 心跳：3 档离散尺寸跳变
  //   对标实测：心形像素面积 864 / 1620 / 2320 三档，
  //   线性尺寸比 ≈ 1 : 1.37 : 1.64，档间**无过渡**（直接换尺寸）。
  //   beat(t)              → 0|1|2 档位
  //   beat(t, 0.42)        → 指定一拍时长（秒）
  //   返回的不是数值而是档位，自己映射到尺寸：
  //     var s = [1, 1.37, 1.64][FX.beat(t)];
  //   节奏建议：小二拍 + 大拍（0,1,0,2）比 0,1,0,1 更像心跳。
  // ══════════════════════════════════════════════════════
  beat: function (t, period) {
    period = period || 0.42;
    var n = Math.floor(t / period) % 4;
    return [0, 1, 0, 2][n];
  },

  // ══════════════════════════════════════════════════════
  // C. 数字乱跳（心跳余额实测：逐帧整串替换，不是里程表滚动）
  //   odo(lt, 12)          → 0..11 的伪随机整数，每帧换
  //   odoNum(lt, 409056204) → 在原值附近 ±0.15% 跳动的整数
  //   为什么不用"逐位滚动"：对标片是整串闪换，滚动版读起来太"金融 APP"。
  // ══════════════════════════════════════════════════════
  odo: function (lt, n, seed) {
    var f = Math.floor(lt * 24);              // 按 24fps 取帧号 = 每帧必变
    var x = Math.sin((f + (seed || 0)) * 127.1) * 43758.5453;
    return Math.floor((x - Math.floor(x)) * (n || 10));
  },
  odoNum: function (lt, base, jitter, seed) {
    jitter = jitter == null ? 0.0015 : jitter;
    var r = (this.odo(lt, 1000, seed) / 500 - 1);   // -1..1
    return Math.max(0, Math.round(base * (1 + r * jitter)));
  },

  // ══════════════════════════════════════════════════════
  // D. 进度条填充（"支付成功"实测：红色横条从左往右填满，恒速）
  //   barFill(lt, 1.2, 100) → 0..100 的长度
  //   barFill 到 1 就停住（不来回扫）——对标片的条填满后是**停在满格**等切镜。
  // ══════════════════════════════════════════════════════
  barFill: function (lt, dur, max) {
    var k = Math.max(0, Math.min(1, lt / dur));
    return Math.round(k * (max == null ? 100 : max));
  },

  // ══════════════════════════════════════════════════════
  // E. 面板滑入（UI 面板从侧边进入）
  //   panelIn(lt, 0.28, -60, 0) → 当前 x 偏移
  //   0.28s 是实测最舒服的时长；更短像闪现，更长拖沓。
  //   对标片用的是**硬起硬停**（无缓动），进门时略过冲 2px 再回正。
  // ══════════════════════════════════════════════════════
  panelIn: function (lt, dur, from, to) {
    dur = dur || 0.28;
    var k = Math.min(1, Math.max(0, lt / dur));
    var over = k >= 1 ? 0 : (k > 0.82 ? -2 * (1 - (k - 0.82) / 0.18) : 0);
    return from + (to - from) * k + over;
  },

  // ══════════════════════════════════════════════════════
  // F. 图标网格逐个点亮（圆形图标阵列实测）
  //   gridOn(i, lt)        → 该格是否处于"亮"状态
  //   规律：每格按自己的相位循环，相邻格错开，
  //   整体读起来像"随机闪烁"，但每格的周期是被锁定的。
  // ══════════════════════════════════════════════════════
  gridOn: function (i, lt, period) {
    period = period || 1.6;
    return ((lt + i * 0.37) % period) < period * 0.35;
  },

  // ══════════════════════════════════════════════════════
  // G. 粒子漂浮（背景氛围）
  //   drift(i, lt, seed)   → {dx, dy, a} 位移与透明度
  //   实测：速度极慢（0.3–0.8 px/s @320 基准），幅度 < 6px，
  //   透明度在 0.2–0.5 之间呼吸。**不能快**，快了像下雪。
  // ══════════════════════════════════════════════════════
  drift: function (i, lt, seed) {
    var s = (seed || 0) + i * 1.7;
    var sp = 0.3 + (i % 5) * 0.1;
    return {
      dx: Math.round(Math.sin(lt * 0.4 + s) * 3),
      dy: Math.round(-((lt * sp + s * 3) % 6)),
      a: 0.2 + 0.3 * (0.5 + 0.5 * Math.sin(lt * 1.1 + s)),
    };
  },

  // ══════════════════════════════════════════════════════
  // H. 入场放大（罗盘开场实测：从 0 放到满屏，0.6s，恒速）
  //   popIn(lt, 0.6, 0, 1)  → 缩放系数
  // ⚠ 用 Math.round 到 0.05 的档位，像素风不许连续缩放。
  // ══════════════════════════════════════════════════════
  popIn: function (lt, dur, from, to) {
    from = from == null ? 0 : from; to = to == null ? 1 : to;
    var k = Math.min(1, Math.max(0, lt / (dur || 0.6)));
    var v = from + (to - from) * k;
    return Math.round(v * 20) / 20;
  },

  // ══════════════════════════════════════════════════════
  // I. 波形滚动（心电图实测：线从左往右滚，超出左边裁掉）
  //   waveX(lt, speed)     → 波形相位偏移
  //   配合 ECG 采样：y = f((x + offset) % len)
  // ══════════════════════════════════════════════════════
  waveX: function (lt, speed) { return Math.round(lt * (speed == null ? 60 : speed)); },

  // ══════════════════════════════════════════════════════
  // J. 故障转场（《恋人》开场实测：蓝红格栅 + 横条位移，0.1–0.2s）
  //   glitch(c, W, H, lt, dur)   在 draw 末尾调用，lt 是本镜已播秒数
  //   dur 建议 0.10–0.20s。超过 0.25s 就变成"特效展示"，不再是转场。
  //   ⚠ 必须在**内容画完之后**调用，它会读当前 canvas。
  //   ⚠ 只对标了"看起来像"，横向条位移量与通道偏移是估的（见拆解卡第 8 节待补）。
  // ══════════════════════════════════════════════════════
  glitch: function (c, W, H, lt, dur) {
    dur = dur || 0.16;
    if (lt < 0 || lt > dur) return;
    var k = 1 - lt / dur;                 // 强度衰减
    // ① 横向条带位移（同 canvas 自绘，需先画完内容）
    var bands = 7;
    for (var i = 0; i < bands; i++) {
      var yb = Math.floor(i * H / bands + Math.sin(lt * 55 + i) * 3);
      var hb = Math.max(1, Math.round(H / bands * 0.45));
      var dx = Math.round(Math.sin(i * 7.3 + lt * 110) * 14 * k);
      if (!dx || yb < 0 || yb + hb > H) continue;
      c.drawImage(c.canvas, 0, yb, W, hb, dx, yb, W, hb);
    }
    // ② 红蓝通道偏移（用错位色条模拟，不做真通道分离）
    c.save();
    c.globalCompositeOperation = 'screen';
    for (var j = 0; j < 5; j++) {
      var yy = Math.floor((((j * 37 + lt * 900) % H) + H) % H);
      c.globalAlpha = 0.30 * k;
      c.fillStyle = (j % 2) ? '#FF2040' : '#20A0FF';
      c.fillRect(0, yy, W, 1);
      c.globalAlpha = 0.16 * k;
      c.fillRect(0, yy + 1, W, 2);
    }
    c.restore();
    // ③ 全屏压暗一档，让撕裂更明显
    c.save(); c.globalAlpha = 0.18 * k; c.fillStyle = '#000000';
    c.fillRect(0, 0, W, H); c.restore();
  },
};
