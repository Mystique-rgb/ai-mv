// Build src/cues.js from the real audio/lyric sources: 11月6日.srt (line windows)
// + 11月6日-逐字时间戳.json (per-character timings) + 11月6日.lrc (metadata).
// The film's subtitles and karaoke timing come from here — nothing is retyped by hand.
import fs from 'fs'; import path from 'path';
const SRC = process.argv[2] || path.resolve('D:/ai音乐mv/爱怎么了');
const OUT = path.resolve(process.argv[3] || 'src/cues.js');

const read = f => fs.readFileSync(path.join(SRC, f), 'utf8').replace(/^\uFEFF/, '');

// —— SRT: the authoritative display windows ——
const srt = read('11月6日.srt').trim().split(/\r?\n\s*\r?\n/).map(block => {
  const L = block.split(/\r?\n/);
  const m = /(\d+):(\d+):(\d+),(\d+)\s*-->\s*(\d+):(\d+):(\d+),(\d+)/.exec(L[1]);
  const s = (+m[1]) * 3600 + (+m[2]) * 60 + (+m[3]) + (+m[4]) / 1000;
  const e = (+m[5]) * 3600 + (+m[6]) * 60 + (+m[7]) + (+m[8]) / 1000;
  return { s, e, text: L.slice(2).join(' ') };
});

// —— Per-character timestamps ——
const J = JSON.parse(read('11月6日-逐字时间戳.json'));

// Merge: SRT line text (punctuation-free display) + char timings from the aligner.
// The aligner's char list contains only the sung characters; the space between two
// phrases is not a character, so we pair them by order and keep the space as a break.
const lines = srt.map((L, i) => {
  const jl = J.lines[i] || {};
  const timed = new Map();
  for (const c of (jl.chars || [])) {
    if (!timed.has(c.c)) timed.set(c.c, []);
    timed.get(c.c).push([c.s, c.e]);
  }
  const chars = [];
  let prev = L.s;
  for (const ch of [...L.text]) {
    if (ch === ' ') { chars.push({ c: ' ', s: prev, e: prev }); continue; }
    const q = timed.get(ch);
    if (q && q.length) {
      const [s, e] = q.shift();
      chars.push({ c: ch, s, e });
      prev = e;
    } else {
      // a character the aligner did not report (rare): inherit the neighbour's window
      chars.push({ c: ch, s: prev, e: prev });
    }
  }
  return { i: i + 1, s: L.s, e: L.e, t: L.text, ch: chars };
});

// The per-character windows must be non-decreasing, and inside the line window.
const warn = [];
for (const L of lines) {
  let last = L.s;
  for (const c of L.ch) {
    if (c.s < L.s - 1e-6) { c.s = L.s; warn.push(`L${L.i} ${c.c} start before line`); }
    if (c.s < last - 0.001) { c.s = last; warn.push(`L${L.i} ${c.c} out of order`); }
    if (c.e < c.s) c.e = c.s;
    last = Math.max(last, c.e);
  }
}

// —— Music grid (from the storyboard's own measurements: 69.36 BPM, bar 1 at 0.08 s) ——
const BPM = 69.36, BEAT = 60 / BPM, BAR = BEAT * 4, B0 = 0.08;
const DUR = 56.87;                 // 52 shots (0.00–55.36) + tail board (55.36–56.87)
const AUDIO = 55.6669;             // ffprobe of 11月6日.MP3

const js = `// GENERATED by render/build_cues.mjs — do not edit by hand.
// Sources: 11月6日.srt (line windows), 11月6日-逐字时间戳.json (character timings).
export const BPM = ${BPM}, BEAT = ${BEAT.toFixed(6)}, BAR = ${BAR.toFixed(6)}, B0 = ${B0};
export const DUR = ${DUR};          // picture length (audio is padded to this)
export const AUDIO_DUR = ${AUDIO};  // real music length
export const beat = n => B0 + n * BEAT;          // absolute time of beat n (0 = first downbeat)
export const bar = n => B0 + n * BAR;            // bar head (n from 1)
export const LINES = ${JSON.stringify(lines, null, 0)};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, js);

// Report
console.log(`lines ${lines.length}  chars ${lines.reduce((a, L) => a + L.ch.length, 0)}  DUR ${DUR}`);
if (warn.length) console.log('warnings:\n  ' + warn.slice(0, 12).join('\n  '));
for (const L of lines) console.log(`L${String(L.i).padStart(2)} ${L.s.toFixed(2)}–${L.e.toFixed(2)}  ${L.t}  [${L.ch.map(c => c.c + c.s.toFixed(2)).join(' ')}]`);
